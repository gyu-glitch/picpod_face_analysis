faces_dir = Path(__file__).resolve().parent.parent / "tests" / "faces"
total_match = total = 0
for name, expected in EXPECTED.items():
    result = analyze_image(cv2.imread(str(faces_dir / f"{name}.jpg")))
    got = result.buckets
    matches = sum(1 for k, v in expected.items() if got.get(k) == v)
    total_match += matches
    total += len(expected)
    print(f"\n[{name}] {matches}/{len(expected)}  유형={result.type.name}({result.type.code})  "
          f"삼정={result.samjeong.upper}/{result.samjeong.mid}/{result.samjeong.lower}({result.samjeong.dominant})")
    for k, v in expected.items():
        if got.get(k) != v:
            print(f"  ✗ {k}: 기대「{v}」 실제「{got.get(k)}」")

print(f"\n=== 전체 일치율: {total_match}/{total} ({100 * total_match / total:.0f}%) ===")
